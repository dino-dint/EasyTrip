export const addDays = (base, n) => {
  const d = new Date(base)
  d.setDate(d.getDate() + n)
  return d
}

export const fmtDay = (d) =>
  d.toLocaleDateString("en-US", {
    weekday: "short",
    month: "short",
    day: "numeric",
  })
  

export const fmtFullDay = (d) =>
  d.toLocaleDateString("en-US", {
    weekday: "long",
    month: "long",
    day: "numeric",
    year: "numeric",
  })


